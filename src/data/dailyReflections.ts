/**
 * دریافت سخن روزانه به صورت قطعی و چرخشی بر اساس روز
 * هر چند روز یک بار کل لیست به طور روان از ابتدا تکرار می‌شود
 */
export const getDailyReflection = (date?: Date): DailyReflection => {
  const d = date || new Date();
  // محاسبه تفاوت روز از مبدا ثابت
  const epoch = new Date(2025, 0, 1).getTime();
  const current = new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
  const dayDifference = Math.floor((current - epoch) / (1000 * 60 * 60 * 24));
  const safeIndex = Math.abs(dayDifference) % DAILY_REFLECTIONS.length;
  return DAILY_REFLECTIONS[safeIndex];
};
